def r(num, den, nd=2):
    q = Decimal(1).scaleb(-nd)
    return str((Decimal(num) * 100 / Decimal(den)).quantize(q, ROUND_HALF_UP))


def rd(x, nd=2):
    return str(Decimal(x).quantize(Decimal(1).scaleb(-nd), ROUND_HALF_UP))


