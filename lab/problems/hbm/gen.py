def wk(d):
    return (d - D0).days // 7


def defects(c, d):
    w, wd = wk(d), d.weekday()
    base = [2, 3, 4, 3, 3]
    if sup(c, d) == "SUP-M":
        base[0] = VW[w]
    if rec(d) == "R275":
        base[1] = 8
    n = [base[t] + Q[(t + w + c % 3) % 6][wd] for t in range(5)]
    if c == 0 and wd == 5:  # 토요일 주간 변동
        n[4] += E[w]
    if c == 0 and wd == 6:  # 일요일 상쇄(주 합계 보존)
        n[4] -= E[w]
    assert min(n) >= 0
    return n


DATA = {(c, d): defects(c, d) for c in range(6) for d in DAYS}


def agg(pred):
    inp, df = 0, [0] * 5
    for (c, d), n in DATA.items():
        if pred(c, d):
            inp += INP
            df = [a + b for a, b in zip(df, n)]
    return {"inp": inp, "df": df, "good": inp - sum(df)}


def y(a):
    return r(a["good"], a["inp"])


