def build(s):
    e = EMP[s["e"]]; ctry, g, cur, mins, quote = CITY[s["city"]]; grp = GROUP[e[3]]
    ret = s["dep"] + timedelta(s["n"])
    rows = [dict(kind="항공료", d=s["dep"], cur="KRW", amt=quote[s["seat"]], rc=True, note=SEATS[s["seat"]])]
    rows.append(dict(kind=f"숙박비({s['n']}박)", d=ret, cur=cur, amt=local(s["hotel"] * s["n"], cur, ret), rc=not s.get("hr"), note=f"체크인 {s['dep']:%m-%d} · 체크아웃 {ret:%m-%d}", n=s["n"]))
    meal = s.get("meal", {})
    for i in range(s["n"] + 1):
        d = s["dep"] + timedelta(i)
        t, rc = meal.get(i, (meal_limit(g, grp, d) * R.uniform(0.55, 0.9), None))
